export const CHICKEN_BY_ID: Record<string, ChickenDef> = Object.fromEntries(
  CHICKENS.map((chicken) => [chicken.id, chicken]),
);

export const STARTER_CHICKENS: readonly string[] = ['henny'];

/** Weighted reward pick that favours chickens the player does not own yet. */
export function rollChicken(
  owned: readonly string[],
  rng: Rng = mulberry32((Math.random() * 0xffffffff) >>> 0),
): ChickenDef {
  const pool = CHICKENS.filter((chicken) => chicken.weight > 0);
  const picked = weightedPick(rng, pool, (chicken) => {
    const base = chicken.weight;
    return owned.includes(chicken.id) ? base * 0.35 : base;
  });
  return picked ?? CHICKENS[0]!;
}
